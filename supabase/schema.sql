-- ---------------------------------------------------------------------------
-- Admin sign-in lives in Supabase Auth (dashboard → Authentication),
-- not in this schema: the app calls supabase.auth.signInWithPassword
-- and the signed-in role gets access through the RLS policies below.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- Row Level Security
-- Every table is readable by any signed-in user; signed-in users (school
-- staff) may also write. Tighten per-table later by adding WITH CHECK /
-- USING clauses based on auth.jwt() claims (e.g. a "role" claim).
-- ---------------------------------------------------------------------------

do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'students','staff','settings',
    'attendance_daily','class_attendance','schedule',
    'activity_log','health_metrics','finance_monthly','fee_categories',
    'invoices','payments','announcements','messages','notifications',
    'exams','exam_results','assignments','transport_routes','vehicles',
    'library_books','timetable','subjects','performance_trend',
    'subject_averages','grade_outcomes','report_exports','settings'
  ] loop
    execute format('alter table public.%I enable row level security', tbl);
  end loop;
end $$;

-- No policies are created here on purpose.
--
-- This file used to grant every signed-in user read and write on every one of
-- these tables. Because the browser talks to Postgres directly, that included
-- pupils and parents: any of them could read invoices, marks and medical notes,
-- and could write to them, from the console. Row level security was enabled and
-- then immediately defeated.
--
-- RLS with no policy denies everything, which is the correct default. Real
-- policies are installed by `supabase/migrations/016_rls_hardening.sql`; run
-- that after this file. The API routes use the service key and are unaffected
-- in the meantime.

-- Explicit privileges so the roles can reach the tables at all. Privileges are
-- only the outer gate; the row-level policy decides which rows are visible.
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on all tables in schema public to authenticated;

-- ---------------------------------------------------------------------------
-- Realtime — surface tables to supabase_realtime so postgres_changes fires
-- (guarded: only adds tables not already in the publication)
-- ---------------------------------------------------------------------------

do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'students','staff','attendance_daily','class_attendance','schedule',
    'activity_log','invoices','payments','announcements','messages',
    'notifications','exams','exam_results','assignments','transport_routes',
    'vehicles','library_books','timetable','subjects'
  ] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = tbl
    ) then
      execute format('alter publication supabase_realtime add table public.%I', tbl);
    end if;
  end loop;
end $$;

